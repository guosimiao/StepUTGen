#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
create_bug_mutpy_pynguin.py

Generate buggy variants with MutPy-Pynguin/MutPy.

Each input JSONL record must contain at least:
    task_num, func_name, description, python_solution

Each mutant output JSONL record contains:
    task_num, func_name, description, buggy_solution, bug_type, bug_line

Additional outputs:
    1. A filtered JSONL containing original samples that produced mutants.
    2. A JSONL containing task_num values for samples that produced mutants.

Recommended environment:
    Python 3.8/3.9 is recommended for compatibility.
    pip install MutPy-Pynguin pyyaml

Usage:
    python scripts/create_bug_mutpy_pynguin.py

Notes:
1. Mutations are generated by MutPy-Pynguin/MutPy.
2. A temporary subject.py and a smoke unittest are created for each sample.
3. Mutated lines from --show-mutants are applied to the original python_solution
   to reconstruct the complete buggy_solution.
4. If target_lines is present, mutations near those lines are preferred.
5. bug_line records the mutation's line number in the original python_solution.
"""

import ast
import json
import os
import random
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

REPO_ROOT = Path(__file__).resolve().parents[1]


# ========= Tunable parameters =========
RANDOM_SEED = 42
MAX_BUGS_PER_SAMPLE = 5
DEDUP_BY_CODE = True

# MutPy timeout per sample in seconds; increase it for complex samples.
MUTPY_TIMEOUT = 120

# Set to True to retain temporary directories for debugging MutPy output.
KEEP_TEMP_DIR = False

# Prefer mutants near target_lines in the dataset.
PREFER_TARGET_LINES = True

# Allowed distance from target_lines; 1 includes line-1, line, and line+1.
TARGET_LINE_WINDOW = 1

# Enable MutPy experimental operators.
# Operators such as SDL (statement deletion) require experimental mode.
USE_EXPERIMENTAL_OPERATORS = True

# Restrict MutPy operators; None uses the default operator set.
# Example:
# MUTPY_OPERATORS = ["AOR", "ROR", "LCR", "CRP", "COD", "COI", "SIR"]
MUTPY_OPERATORS: Optional[List[str]] = None

# Disable selected MutPy operators.
# Add SDL to exclude statement-deletion mutants for function-level tasks.
DISABLE_MUTPY_OPERATORS: Optional[List[str]] = None

# Include the line number in bug_type; False produces mutpy_AOR.
# True produces names such as mutpy_AOR_line_23.
INCLUDE_LINE_IN_BUG_TYPE = True


random.seed(RANDOM_SEED)


# ========= JSONL utilities =========
def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    data: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                data.append(json.loads(line))
            except json.JSONDecodeError as e:
                print(f"[WARN] line {line_no} JSON decode failed: {e}")
    return data


def write_jsonl(path: Path, data: List[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for item in data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")


def default_filtered_output_path(input_file: Path, output_file: Path) -> Path:
    suffix = output_file.suffix or ".jsonl"
    return output_file.with_name(f"{input_file.stem}_with_mutants{suffix}")


def default_task_nums_output_path(output_file: Path) -> Path:
    suffix = output_file.suffix or ".jsonl"
    return output_file.with_name(f"{output_file.stem}_task_nums{suffix}")


def is_valid_python(code: str) -> bool:
    try:
        compile(code, "<string>", "exec")
        return True
    except Exception:
        return False


# ========= MutPy result types =========
@dataclass
class MutantCandidate:
    mutant_no: int
    operator: str
    source_file: str
    first_line: Optional[int]
    replacements: List[Tuple[int, str]]
    raw_block: str

    @property
    def bug_type(self) -> str:
        if INCLUDE_LINE_IN_BUG_TYPE and self.first_line is not None:
            return f"mutpy_{self.operator}_line_{self.first_line}"
        return f"mutpy_{self.operator}"


# ========= Environment and command utilities =========
def find_mutpy_command() -> List[str]:
    """
    Support both MutPy-Pynguin and MutPy installations.
    Common entry point:
        mut.py
    Fallback when unavailable:
        python -m mutpy.commandline
    """
    mut_py = shutil.which("mut.py")
    if mut_py:
        return [mut_py]

    # mut.py may not be executable on Windows or in some environments.
    # Use python -m mutpy.commandline as a fallback.
    return [sys.executable, "-m", "mutpy.commandline"]


def detect_mutpy_version() -> Optional[str]:
    """
    Return the installed version. The distribution is named MutPy-Pynguin,
    while its import module is usually mutpy.
    """
    code = (
        "import importlib.metadata as m\n"
        "for name in ['MutPy-Pynguin', 'mutpy', 'MutPy']:\n"
        "    try:\n"
        "        print(name + '==' + m.version(name))\n"
        "        break\n"
        "    except Exception:\n"
        "        pass\n"
    )
    try:
        p = subprocess.run(
            [sys.executable, "-c", code],
            text=True,
            capture_output=True,
            timeout=10,
        )
    except Exception:
        return None

    if p.returncode != 0:
        return None

    out = p.stdout.strip()
    return out or None


def run_cmd(
    cmd: Sequence[str],
    cwd: Path,
    timeout: int = MUTPY_TIMEOUT,
) -> subprocess.CompletedProcess:
    env = os.environ.copy()
    # Put the temporary directory first on the import path.
    current_pythonpath = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = str(cwd) + (os.pathsep + current_pythonpath if current_pythonpath else "")

    return subprocess.run(
        list(cmd),
        cwd=str(cwd),
        text=True,
        capture_output=True,
        timeout=timeout,
        env=env,
    )


# ========= Temporary project construction =========
def write_sortedcontainers_stub(work_dir: Path) -> None:
    """
    Some LeetCode solutions import sortedcontainers at module scope.
    Without that dependency, MutPy cannot import subject.py.
    Write a minimal stub to allow module imports to succeed.
    """
    stub = work_dir / "sortedcontainers.py"
    if stub.exists():
        return

    stub.write_text(
        "class SortedList(list):\n"
        "    def add(self, x): self.append(x); self.sort()\n\n"
        "class SortedSet(set):\n"
        "    def add(self, x): super().add(x)\n\n"
        "class SortedDict(dict):\n"
        "    pass\n",
        encoding="utf-8",
    )


def prepare_mutpy_project(work_dir: Path, code: str) -> None:
    """
    Build a temporary project for one sample:
        work_dir/
            subject.py
            test_subject.py
            sortedcontainers.py   optional stub
    """
    (work_dir / "subject.py").write_text(code, encoding="utf-8")
    write_sortedcontainers_stub(work_dir)

    # The smoke test checks that the original subject.py can be imported.
    # Mutants are subsequently checked through compilation and deduplication.
    test_code = """
import unittest

class SmokeTest(unittest.TestCase):
    def test_import_subject(self):
        try:
            import subject  # noqa: F401
        except Exception as e:
            self.fail(f"subject import failed: {e}")

if __name__ == "__main__":
    unittest.main()
"""
    (work_dir / "test_subject.py").write_text(test_code.strip() + "\n", encoding="utf-8")


# ========= MutPy output parsing =========
_MUTANT_HEADER_RE = re.compile(
    r"\[#\s*(?P<num>\d+)\]\s+"
    r"(?P<op>[A-Z][A-Z0-9]*)\s+"
    r"(?P<file>[^:\s]+)(?::(?P<line>\d+))?"
)

# Example MutPy-Pynguin show-mutants output:
#     ~2:     return x / y
#     1: def mul(x, y):
# Also support the +/- diff format emitted by some versions:
#     +  2:     return x / y
#     -  2:     return x * y
_MUTATED_LINE_RE_LIST = [
    re.compile(r"^\s*~\s*(?P<line>\d+)\s*:\s?(?P<code>.*)$"),
    re.compile(r"^\s*\+\s*(?P<line>\d+)\s*:\s?(?P<code>.*)$"),
]


def _parse_mutated_line(line: str) -> Optional[Tuple[int, str]]:
    for pattern in _MUTATED_LINE_RE_LIST:
        m = pattern.match(line.rstrip("\n"))
        if m:
            return int(m.group("line")), m.group("code")
    return None


def parse_mutpy_show_mutants_output(text: str) -> List[MutantCandidate]:
    """
    Parse candidate mutants from MutPy/MutPy-Pynguin --show-mutants output.
    Each block extends from a [# n] header to the next [# n+1] header.
    """
    lines = text.splitlines()
    header_indices: List[Tuple[int, re.Match]] = []

    for idx, line in enumerate(lines):
        m = _MUTANT_HEADER_RE.search(line)
        if m:
            header_indices.append((idx, m))

    candidates: List[MutantCandidate] = []

    for pos, (start_idx, header_match) in enumerate(header_indices):
        end_idx = header_indices[pos + 1][0] if pos + 1 < len(header_indices) else len(lines)
        block_lines = lines[start_idx:end_idx]
        raw_block = "\n".join(block_lines)

        replacements: List[Tuple[int, str]] = []
        for block_line in block_lines:
            parsed = _parse_mutated_line(block_line)
            if parsed is not None:
                replacements.append(parsed)

        if not replacements:
            continue

        try:
            mutant_no = int(header_match.group("num"))
        except Exception:
            mutant_no = -1

        line_from_header: Optional[int]
        try:
            line_from_header = int(header_match.group("line")) if header_match.group("line") else None
        except Exception:
            line_from_header = None

        first_line = line_from_header if line_from_header is not None else replacements[0][0]

        candidates.append(
            MutantCandidate(
                mutant_no=mutant_no,
                operator=header_match.group("op"),
                source_file=header_match.group("file"),
                first_line=first_line,
                replacements=replacements,
                raw_block=raw_block,
            )
        )

    return candidates


def apply_line_replacements(original_code: str, replacements: List[Tuple[int, str]]) -> Optional[str]:
    """
    Apply the mutated lines printed by MutPy to reconstruct the full mutant source.

    Notes:
    - show-mutants displays source lines, usually for a single-point mutation.
    - Replacements spanning multiple lines are also supported.
    """
    original_lines = original_code.splitlines()

    if not original_lines:
        return None

    new_lines = original_lines[:]

    for line_no, new_content in replacements:
        if line_no <= 0 or line_no > len(new_lines):
            return None

        # Content after the colon in MutPy output already includes indentation.
        new_lines[line_no - 1] = new_content

    new_code = "\n".join(new_lines)
    if original_code.endswith("\n"):
        new_code += "\n"

    if new_code.strip() == original_code.strip():
        return None

    if not is_valid_python(new_code):
        return None

    return new_code


def target_line_score(candidate: MutantCandidate, target_lines: Optional[Iterable[int]]) -> int:
    """
    Rank mutants near target_lines first.
    Lower scores have higher priority.
    """
    if not PREFER_TARGET_LINES:
        return 0

    if not target_lines:
        return 1

    if candidate.first_line is None:
        return 1

    target_set = set()
    for line in target_lines:
        try:
            line_int = int(line)
        except Exception:
            continue
        for delta in range(-TARGET_LINE_WINDOW, TARGET_LINE_WINDOW + 1):
            target_set.add(line_int + delta)

    return 0 if candidate.first_line in target_set else 1


def filter_and_rank_candidates(
    candidates: List[MutantCandidate],
    sample: Dict[str, Any],
) -> List[MutantCandidate]:
    """
    Filter and sort candidate mutants.
    Killed/survived status is ignored because the smoke test is not a full test suite.
    Rank by source reconstructability, target-line proximity, and random tie breaking.
    """
    # Keep mutants of subject.py and exclude mutations of test_subject.py.
    filtered = [
        c for c in candidates
        if Path(c.source_file).name == "subject.py"
        or c.source_file in {"subject", "subject.py"}
        or c.source_file.endswith("subject.py")
    ]

    target_lines = sample.get("target_lines")
    # Break ties randomly to avoid repeatedly selecting the first operator types.
    ranked = sorted(
        filtered,
        key=lambda c: (
            target_line_score(c, target_lines),
            random.random(),
            c.mutant_no,
        ),
    )
    return ranked


# ========= Core generation logic =========
def run_mutpy_for_sample(
    sample: Dict[str, Any],
    work_dir: Path,
    timeout: int = MUTPY_TIMEOUT,
) -> Tuple[List[MutantCandidate], str, str, int]:
    """
    Run MutPy and return candidate mutants.
    """
    prepare_mutpy_project(work_dir, sample["python_solution"])

    mutpy_cmd = find_mutpy_command()
    cmd: List[str] = [
        *mutpy_cmd,
        "--target", "subject",
        "--unit-test", "test_subject",
        "--runner", "unittest",
        "--show-mutants",
        "--path", str(work_dir),
        "--timeout-factor", "5",
    ]

    if USE_EXPERIMENTAL_OPERATORS:
        cmd.append("--experimental-operators")

    if MUTPY_OPERATORS:
        cmd.append("--operator")
        cmd.extend(MUTPY_OPERATORS)

    if DISABLE_MUTPY_OPERATORS:
        cmd.append("--disable-operator")
        cmd.extend(DISABLE_MUTPY_OPERATORS)

    p = run_cmd(cmd, cwd=work_dir, timeout=timeout)
    output = (p.stdout or "") + "\n" + (p.stderr or "")
    candidates = parse_mutpy_show_mutants_output(output)

    return candidates, p.stdout or "", p.stderr or "", p.returncode


def generate_buggy_variants(
    sample: Dict[str, Any],
    max_bugs: int = MAX_BUGS_PER_SAMPLE,
    mutpy_timeout: int = MUTPY_TIMEOUT,
    keep_temp_dir: bool = KEEP_TEMP_DIR,
) -> List[Dict[str, Any]]:
    """
    Generate buggy variants with mutation line numbers from one correct sample.
    """
    code = sample["python_solution"]

    if not is_valid_python(code):
        print(f"[WARN] task {sample.get('task_num')} original python_solution is invalid. Skip.")
        return []

    temp_obj = tempfile.TemporaryDirectory(prefix=f"mutpy_task_{sample.get('task_num', 'unknown')}_")
    work_dir = Path(temp_obj.name)

    generated: List[Dict[str, Any]] = []
    seen_codes = set()

    try:
        try:
            candidates, stdout, stderr, returncode = run_mutpy_for_sample(
                sample=sample,
                work_dir=work_dir,
                timeout=mutpy_timeout,
            )
        except subprocess.TimeoutExpired:
            print(f"[WARN] task {sample.get('task_num')} MutPy timeout.")
            return []
        except FileNotFoundError:
            raise RuntimeError(
                "Cannot find MutPy/MutPy-Pynguin command `mut.py`.\n"
                "Please install it first, for example:\n"
                "    pip install MutPy-Pynguin pyyaml\n"
                "If `mut.py` is not on PATH, try running with the Python environment where it is installed."
            )

        if returncode != 0 and not candidates:
            short_msg = (stdout + "\n" + stderr).strip()
            print(f"[WARN] task {sample.get('task_num')} MutPy returned {returncode} and no candidates were parsed.")
            if short_msg:
                print(short_msg[:1200])
            return []

        candidates = filter_and_rank_candidates(candidates, sample)

        for cand in candidates:
            buggy_code = apply_line_replacements(code, cand.replacements)
            if buggy_code is None:
                continue

            if DEDUP_BY_CODE and buggy_code in seen_codes:
                continue

            seen_codes.add(buggy_code)

            # bug_line is the mutation's line number in the original python_solution.
            new_item = {
                "task_num": sample["task_num"],
                "func_name": sample["func_name"],
                "description": sample["description"],
                "buggy_solution": buggy_code,
                "bug_type": cand.bug_type,
                "bug_line": cand.first_line,
            }

            generated.append(new_item)

            if len(generated) >= max_bugs:
                break

        return generated

    finally:
        if keep_temp_dir:
            print(f"[INFO] keep temp dir: {work_dir}")
        else:
            temp_obj.cleanup()


def create_bug(
    input_path: str = "correct_solutions.jsonl",
    output_path: str = "buggy_solutions.jsonl",
    max_bugs_per_sample: int = MAX_BUGS_PER_SAMPLE,
    mutpy_timeout: int = MUTPY_TIMEOUT,
    filtered_output_path: Optional[str] = None,
    task_nums_output_path: Optional[str] = None,
) -> None:
    input_file = Path(input_path)
    output_file = Path(output_path)
    filtered_output_file = (
        Path(filtered_output_path)
        if filtered_output_path is not None
        else default_filtered_output_path(input_file, output_file)
    )
    task_nums_output_file = (
        Path(task_nums_output_path)
        if task_nums_output_path is not None
        else default_task_nums_output_path(output_file)
    )

    version = detect_mutpy_version()
    if version:
        print(f"[INFO] Detected mutation tool: {version}")
    else:
        print("[WARN] MutPy/MutPy-Pynguin package was not detected by importlib.metadata.")
        print("       Recommended installation: pip install MutPy-Pynguin pyyaml")

    samples = read_jsonl(input_file)
    print(f"[INFO] Loaded {len(samples)} correct samples from {input_file}")

    all_buggy_samples: List[Dict[str, Any]] = []
    filtered_samples: List[Dict[str, Any]] = []
    successful_task_nums: List[Dict[str, Any]] = []
    seen_success_task_nums = set()
    success_count = 0

    required_keys = {"task_num", "func_name", "description", "python_solution"}

    for idx, sample in enumerate(samples, 1):
        if not required_keys.issubset(sample.keys()):
            print(f"[WARN] Skip sample due to missing keys: {sample}")
            continue

        buggy_variants = generate_buggy_variants(
            sample=sample,
            max_bugs=max_bugs_per_sample,
            mutpy_timeout=mutpy_timeout,
            keep_temp_dir=KEEP_TEMP_DIR,
        )

        if buggy_variants:
            success_count += 1
            all_buggy_samples.extend(buggy_variants)
            filtered_samples.append(sample)
            task_num_key = str(sample["task_num"])
            if task_num_key not in seen_success_task_nums:
                seen_success_task_nums.add(task_num_key)
                successful_task_nums.append({"task_num": sample["task_num"]})
        else:
            print(f"[WARN] task {sample.get('task_num')} generated 0 buggy variants.")

        if idx % 50 == 0:
            print(
                f"[INFO] processed {idx}/{len(samples)}, "
                f"success_samples={success_count}, "
                f"filtered_samples={len(filtered_samples)}, "
                f"buggy_total={len(all_buggy_samples)}"
            )

    write_jsonl(output_file, all_buggy_samples)
    write_jsonl(filtered_output_file, filtered_samples)
    write_jsonl(task_nums_output_file, successful_task_nums)

    print(f"[INFO] {success_count} / {len(samples)} samples generated at least one buggy variant.")
    print(f"[INFO] Total buggy samples: {len(all_buggy_samples)}")
    print(f"[INFO] Filtered correct samples: {len(filtered_samples)}")
    print(f"[INFO] Successful task nums: {len(successful_task_nums)}")
    print(f"[INFO] Mutants saved to: {output_file}")
    print(f"[INFO] Filtered dataset saved to: {filtered_output_file}")
    print(f"[INFO] Task nums saved to: {task_nums_output_file}")


if __name__ == "__main__":
    input_path = str(REPO_ROOT / "data/mutpy_train/alldataset.jsonl")
    output_path = str(REPO_ROOT / "data/mutpy_train/alldataset_mutpy.jsonl")
    filtered_output_path = str(REPO_ROOT / "data/mutpy_train/alldataset_filter.jsonl")
    task_nums_output_path = str(REPO_ROOT / "data/mutpy_train/alldataset_mutpy_task_nums.jsonl")

    create_bug(
        input_path=input_path,
        output_path=output_path,
        filtered_output_path=filtered_output_path,
        task_nums_output_path=task_nums_output_path,
        max_bugs_per_sample=MAX_BUGS_PER_SAMPLE,
        mutpy_timeout=MUTPY_TIMEOUT,
    )
